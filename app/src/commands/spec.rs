//! `sisho spec`: CLI command reference generator from clap definitions.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use anyhow::Result;
use clap::CommandFactory;
use tomet_spec::PrinterConfig;

use super::{Sink, finish, with_standard_streams};
use crate::cli::{Cli, SpecArgs, SpecTarget};

const DOC_ID: &str = "doc-cliDocRf";
const NOTICE: &str = "Generated by `sisho spec cli` from the clap definitions in \
     `app/src/cli.rs`. Do not edit it: change the doc comments there and run \
     the command again.";

pub fn spec(args: &SpecArgs) -> ExitCode {
    finish(with_standard_streams(|out, _err| run_spec(args, out)))
}

pub fn run_spec(args: &SpecArgs, out: Sink<'_>) -> Result<()> {
    let target = args.target.unwrap_or(SpecTarget::Cli);
    let (rendered, filename, target_name) = match target {
        SpecTarget::Cli => (
            render_cli(&config_for_output(args.out.as_deref())),
            "cli.tmt",
            "cli",
        ),
    };

    let Some(out_arg) = args.out.as_deref() else {
        write!(out, "{rendered}")?;
        return Ok(());
    };

    let out_path = resolve_target_file(out_arg, filename);
    write_or_check(&out_path, &rendered, args.check, target_name, out)
}

/// Renders the complete formatted CLI specification `.tmt` string.
pub fn render_cli(config: &PrinterConfig) -> String {
    let mut root = Cli::command();
    tomet_spec::cli::render(&mut root, DOC_ID, NOTICE, config)
}

fn config_for_output(out: Option<&Path>) -> PrinterConfig {
    let probe: PathBuf = out.map_or_else(|| PathBuf::from("."), Path::to_path_buf);
    tomet_load_config::find_config_file(&probe)
        .map_or_else(PrinterConfig::default, |(config, _, _)| config)
}

fn resolve_target_file(out: &Path, default_name: &str) -> PathBuf {
    if out.is_dir() || out.extension().is_none() {
        out.join(default_name)
    } else {
        out.to_path_buf()
    }
}

fn write_or_check(
    path: &Path,
    content: &str,
    check: bool,
    target: &str,
    out: Sink<'_>,
) -> Result<()> {
    if check {
        return match fs::read_to_string(path) {
            Ok(current) if current == content => Ok(()),
            Ok(_) => Err(anyhow::anyhow!(
                "{} is out of date; regenerate it with `sisho spec {} --out {}`",
                path.display(),
                target,
                path.display()
            )),
            Err(e) => Err(anyhow::anyhow!(
                "cannot read {}: {e}; generate it with `sisho spec {} --out {}`",
                path.display(),
                target,
                path.display()
            )),
        };
    }

    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, content)?;
    writeln!(out, "Wrote {}", path.display())?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use tomet_ast::{Block, Document};

    fn document() -> Document {
        let mut root = Cli::command();
        root.build();
        tomet_spec::cli::document(&mut root, DOC_ID, NOTICE)
    }

    fn rendered() -> String {
        render_cli(&PrinterConfig::default())
    }

    #[test]
    fn every_subcommand_is_in_the_reference() {
        let text = rendered();
        let mut root = Cli::command();
        root.build();
        for sub in root.get_subcommands().filter(|s| s.get_name() != "help") {
            assert!(
                text.contains(&format!("sisho {}", sub.get_name())),
                "missing section for `{}`",
                sub.get_name()
            );
        }
        assert!(text.contains("--jobs"), "global options are listed");
    }

    #[test]
    fn the_output_is_valid_tmt_and_deterministic() {
        let text = rendered();
        tomet_parser::parse_document(&text).expect("the generated reference parses");
        assert_eq!(text, rendered());
    }

    #[test]
    fn reading_the_output_back_keeps_every_paragraph_and_section() {
        fn count(blocks: &[Block], sections: &mut usize, paragraphs: &mut usize) {
            for block in blocks {
                match block {
                    Block::Section(s) => {
                        *sections += 1;
                        count(&s.blocks, sections, paragraphs);
                    }
                    Block::Paragraph(_) => *paragraphs += 1,
                    Block::Element(_) | Block::List(_) => {}
                }
            }
        }
        let (mut want_s, mut want_p) = (0, 0);
        count(&document().blocks, &mut want_s, &mut want_p);

        let parsed = tomet_parser::parse_document(&rendered()).unwrap();
        let (mut got_s, mut got_p) = (0, 0);
        count(&parsed.blocks, &mut got_s, &mut got_p);
        assert_eq!((got_s, got_p), (want_s, want_p));
    }
}
